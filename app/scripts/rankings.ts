/**
 * Generate docs/RANKINGS.md from public/data/rfps.json using the same scoring code as the app.
 *   node --experimental-strip-types scripts/rankings.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { enrich } from '../src/lib/score.ts'
import type { Rfp } from '../src/types.ts'

const { meta, rfps } = JSON.parse(readFileSync(new URL('../public/data/rfps.json', import.meta.url), 'utf8')) as { meta: { source: string }; rfps: Rfp[] }
const nodes = enrich(rfps).filter((n) => n.status !== 'Closed')
const asOf = '2026-10-13'
const cell = (s: string | null | undefined) => (s ?? '—').replace(/\|/g, '/')
const usd = (v: number | null) => (v == null ? 'not published' : `$${v.toLocaleString()}`)

const byFit = [...nodes].sort((a, b) => b.aiFit - a.aiFit || (a.daysLeft ?? 999) - (b.daysLeft ?? 999))
const digital = byFit.filter((n) => n.aiFit >= 60)

let md = `# Opportunity rankings

*Generated by \`app/scripts/rankings.ts\` from \`app/public/data/rfps.json\` (${nodes.length} open/planned solicitations, closed ones excluded). As of ${asOf}.*
*Source: ${meta.source}.*

> **Data caveat.** This sandbox's network policy blocks passport.cityofnewyork.us, so this seed was assembled from search-indexed copies of the PASSPort browse grid, the Databook mirror and City Record notices. Run \`npm run scrape\` from an unrestricted network to replace it with the full live grid. Fields marked *inferred* weren't present in the source.

## 1. Fully digital software builds (AI-fit ≥ 60)

These are the opportunities where an AI-assisted team could produce most or all of the deliverable: software, data and digital-service work with no physical construction or in-person service delivery.

| # | AI fit | Title | Agency | EPIN | Due | Days left | Value | Conf. |
|---|---|---|---|---|---|---|---|---|
${digital.map((n, i) => `| ${i + 1} | **${n.aiFit}** | ${cell(n.title)} | ${cell(n.agency)} | ${cell(n.epin)} | ${cell(n.dueDate)} | ${n.daysLeft ?? '—'} | ${usd(n.estValueUSD)} | ${n.confidence} |`).join('\n')}

## 2. Every open opportunity ranked by AI fit

| # | AI fit | Title | Agency | Industry | Due | Value |
|---|---|---|---|---|---|---|
${byFit.map((n, i) => `| ${i + 1} | ${n.aiFit} | ${cell(n.title)} | ${cell(n.agency)} | ${cell(n.industry)}${n.industryInferred ? ' *(inferred)*' : ''} | ${cell(n.dueDate)} | ${usd(n.estValueUSD)} |`).join('\n')}

## 3. Ranked by contract value

**No solicitation in the current dataset has a published dollar value.** PASSPort's browse grid doesn't show estimated contract values, and none of the indexed City Record notices for these EPINs stated one. Rather than invent figures, the value ranking is left empty until one of these sources is added (all are in Phase 2 of the roadmap):

1. **Solicitation documents.** Many RFPs state an "anticipated contract amount" or budget range in the PDF on the PASSPort detail page. The detail-page scraper downloads the PDF and extracts it.
2. **City Record award notices / Checkbook NYC.** Prior awards under the same program or commodity give a reliable proxy (e.g. the predecessor contract value).
3. **Agency procurement plans.** The annual plans published by MOCS list an estimated value per planned procurement.

Once values exist, this section ranks by \`estValueUSD\` and adds a combined score of fit × log(value).

## How AI fit is scored

The score is a transparent heuristic (\`app/src/lib/score.ts\`). It starts at a base of 35, adds weight for software, data, AI and digital keywords, subtracts weight for construction, goods and in-person service keywords, and applies a prior based on PASSPort Industry (e.g. *Professional Services - IT Related* +14, *Construction* −20). Every adjustment is shown in the node's side panel. Phase 3 replaces it with an LLM classifier run over the full solicitation text.
`
writeFileSync(new URL('../../docs/RANKINGS.md', import.meta.url), md)
console.log(`digital: ${digital.length}, total: ${nodes.length}`)
